-- ---------- cheques ----------
create table if not exists public.cheques (
  id              bigint generated by default as identity primary key,
  account_id      int not null references public.cheque_accounts(id),
  bank_id         int references public.cheque_banks(id),
  book_no         text,                          -- no_book (เล่มที่)
  cheque_no       text not null,                 -- no_check
  cheque_date     date not null,                 -- date_check
  payee           text not null default '',      -- payable
  amount          numeric(14,2) not null default 0, -- amont
  detail          text,                          -- act_detail
  crossing        text check (crossing in ('ac','nonac')),  -- A/C Payee only or not (chosen by user)
  status          text not null default 'normal' check (status in ('normal','cancelled')),
  cancel_date     date,                          -- date_rub
  cancel_amount   numeric(14,2),                 -- money_rub
  cancel_reason   text,                          -- detail_rub
  -- budget cheques (paid.xls)
  fiscal_year     text, budget_source text, activity_code text, bill_no text, job_no text, budget_total numeric(14,2),
  print_count     int not null default 0,
  printed_at      timestamptz,
  legacy_source   text,
  legacy_key      text,                          -- "<file>:<row>" for imported rows (makes re-imports safe)
  created_by      uuid default auth.uid(),
  created_by_name text,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);
alter table public.cheques add column if not exists legacy_key text;
-- ช่องกรอกเพิ่มเติมที่กำหนดในแบบฟอร์มเช็ค {"key": {"label": "...", "value": "..."}}
alter table public.cheques add column if not exists extra jsonb;
create unique index if not exists cheques_legacy_key_uq on public.cheques (legacy_key);
create index if not exists cheques_date_idx    on public.cheques (cheque_date desc, id desc);
create index if not exists cheques_account_idx on public.cheques (account_id, bank_id, cheque_date desc);
create index if not exists cheques_no_idx      on public.cheques (cheque_no);
create index if not exists cheques_search_idx  on public.cheques using gin ((cheque_no || ' ' || payee || ' ' || coalesce(detail,'')) gin_trgm_ops);

-- ---------- per-user cheque forms (positions of every item) ----------
--  A copy is an independent row: deleting the original never affects copies
--  (source_form_id is informational only, no foreign key).
create table if not exists public.cheque_forms (
  id               bigint generated by default as identity primary key,
  user_id          uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  user_name        text,
  bank_id          int not null references public.cheque_banks(id),
  name             text not null,
  layout           jsonb not null,
  is_default       boolean not null default false,
  source_form_id   bigint,
  source_form_name text,
  source_user_name text,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
-- crossing = which cheque type the form is for: 'ac' / 'nonac' / 'both' (one default per user + bank + type)
alter table public.cheque_forms add column if not exists crossing text not null default 'both';
alter table public.cheque_forms drop constraint if exists cheque_forms_crossing_chk;
alter table public.cheque_forms add constraint cheque_forms_crossing_chk check (crossing in ('ac','nonac','both'));
create index if not exists cheque_forms_user_idx on public.cheque_forms (user_id, bank_id);
drop index if exists public.cheque_forms_default_uq;
create unique index if not exists cheque_forms_default2_uq on public.cheque_forms (user_id, bank_id, crossing) where is_default;

-- ---------- print log ----------
create table if not exists public.cheque_print_logs (
  id              bigint generated by default as identity primary key,
  cheque_id       bigint not null references public.cheques(id) on delete cascade,
  form_id         bigint,
  form_name       text,
  crossing        text,
  printed_at      timestamptz not null default now(),
  printed_by      uuid default auth.uid(),
  printed_by_name text
);
create index if not exists cheque_print_logs_at_idx on public.cheque_print_logs (printed_at);

-- ---------- functions ----------
create or replace function public.cheques_touch() returns trigger language plpgsql as $$
begin new.updated_at := now(); return new; end $$;
drop trigger if exists cheques_touch on public.cheques;
create trigger cheques_touch before update on public.cheques for each row execute function public.cheques_touch();

create or replace function public.mark_cheques_printed(p_ids bigint[], p_form_id bigint, p_crossing text)
returns int language plpgsql security definer set search_path = public as $$
declare n int; me text; fname text;
begin
  if not public.is_cheque_user() then raise exception 'ไม่มีสิทธิ์ใช้งานระบบเช็ค'; end if;
  select coalesce(full_name, email) into me from public.profiles where id = auth.uid();
  select name into fname from public.cheque_forms where id = p_form_id;
  update public.cheques set print_count = print_count + 1, printed_at = now(),
         crossing = coalesce(p_crossing, crossing)
   where id = any(p_ids) and status = 'normal';
  get diagnostics n = row_count;
  insert into public.cheque_print_logs (cheque_id, form_id, form_name, crossing, printed_by_name)
    select id, p_form_id, fname, p_crossing, me from public.cheques where id = any(p_ids) and status = 'normal';
  return n;
end $$;

create or replace function public.cancel_cheque(p_id bigint, p_reason text)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_cheque_user() then raise exception 'ไม่มีสิทธิ์ใช้งานระบบเช็ค'; end if;
  update public.cheques set status = 'cancelled', cancel_date = (now() at time zone 'Asia/Bangkok')::date,
         cancel_amount = amount, cancel_reason = nullif(trim(p_reason), '')
   where id = p_id and status = 'normal';
  if not found then raise exception 'ไม่พบเช็ค หรือเช็คถูกยกเลิกแล้ว'; end if;
end $$;

-- ---------- Row Level Security ----------
alter table public.cheque_banks      enable row level security;
alter table public.cheque_accounts   enable row level security;
alter table public.cheques           enable row level security;
alter table public.cheque_forms      enable row level security;
alter table public.cheque_print_logs enable row level security;

do $$
declare t text;
begin
  foreach t in array array['cheque_banks','cheque_accounts','cheques','cheque_forms','cheque_print_logs'] loop
    execute format('drop policy if exists "%1$s read" on public.%1$s', t);
    execute format('create policy "%1$s read" on public.%1$s for select to authenticated using (public.is_cheque_user())', t);
    execute format('drop policy if exists "%1$s admin" on public.%1$s', t);
    execute format('create policy "%1$s admin" on public.%1$s for all to authenticated using (public.is_admin()) with check (public.is_admin())', t);
  end loop;
end $$;

-- cheque users: add / edit cheques (cancel via cancel_cheque)
drop policy if exists "cheques user insert" on public.cheques;
create policy "cheques user insert" on public.cheques for insert to authenticated with check (public.is_cheque_user());
drop policy if exists "cheques user update" on public.cheques;
create policy "cheques user update" on public.cheques for update to authenticated
  using (public.is_cheque_user() and status = 'normal') with check (public.is_cheque_user());

-- forms: everyone (cheque users) can see to copy; only the owner changes / deletes
drop policy if exists "forms insert own" on public.cheque_forms;
create policy "forms insert own" on public.cheque_forms for insert to authenticated with check (public.is_cheque_user() and user_id = auth.uid());
drop policy if exists "forms update own" on public.cheque_forms;
create policy "forms update own" on public.cheque_forms for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
drop policy if exists "forms delete own" on public.cheque_forms;
create policy "forms delete own" on public.cheque_forms for delete to authenticated using (user_id = auth.uid() or public.is_admin());

grant execute on function public.mark_cheques_printed(bigint[], bigint, text), public.cancel_cheque(bigint, text) to authenticated;
