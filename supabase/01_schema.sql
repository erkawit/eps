-- ---------------------------------------------------------------------
-- 8) Storage bucket for backups (folders: ปี พ.ศ. / เดือน / วันที่)
-- ---------------------------------------------------------------------
do $$
begin
  if exists (select 1 from information_schema.schemata where schema_name = 'storage') then
    insert into storage.buckets (id, name, public) values ('backups', 'backups', false)
      on conflict (id) do nothing;
    execute 'drop policy if exists "backups admin" on storage.objects';
    execute $p$create policy "backups admin" on storage.objects for all to authenticated
             using (bucket_id = 'backups' and public.is_admin())
             with check (bucket_id = 'backups' and public.is_admin())$p$;
  end if;
end $$;
