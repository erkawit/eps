  using gin ((coalesce(code,'') || ' ' || name || ' ' || coalesce(address,'') || ' ' || coalesce(amphur,'')) gin_trgm_ops);

-- ---------------------------------------------------------------------
-- 3) Outgoing-letter register (G2G e-Saraban style)
--    books   = registry book that issues running numbers per year
--    letters = one row per issued number (one envelope)
-- ---------------------------------------------------------------------
create table if not exists public.books (
  id         serial primary key,
  name       text not null,                       -- e.g. ทะเบียนหนังสือส่งภายนอก
  prefix     text not null,                       -- e.g. ศย 304.019
  year       int  not null,                       -- Buddhist year e.g. 2569
  next_no    int  not null default 1 check (next_no > 0),
  auto_reset boolean not null default true,       -- restart at 1 when the Buddhist year changes
  active     boolean not null default true,
  created_at timestamptz default now()
);

create table if not exists public.letters (
  id                 bigint generated by default as identity primary key,
  book_id            int not null references public.books(id),
  year               int not null,
  doc_no             int not null,
  doc_number         text not null,               -- e.g. ศย 304.019/1234
  customer_id        bigint references public.customers(id) on delete set null,
  recipient_name     text not null,
  recipient_address  text,
  recipient_amphur   text,
  recipient_province text,
  recipient_postcode text,
  subject            text,
  urgency            text not null default 'ปกติ' check (urgency in ('ปกติ','ด่วน','ด่วนมาก','ด่วนที่สุด')),
  envelope           text not null default 'white' check (envelope in ('white','brown')),
  status             text not null default 'issued' check (status in ('issued','printed','cancelled')),
  print_count        int not null default 0,
  printed_at         timestamptz,
  cancel_reason      text,
  created_by         uuid default auth.uid(),
  created_by_name    text,
  created_at         timestamptz not null default now(),
  unique (book_id, year, doc_no)
);
create index if not exists letters_created_idx on public.letters (created_at desc);
create index if not exists letters_book_idx    on public.letters (book_id, year, doc_no);

-- every print of every envelope (used by the print reports)
create table if not exists public.print_logs (
  id              bigint generated by default as identity primary key,
  letter_id       bigint not null references public.letters(id) on delete cascade,
  envelope        text not null check (envelope in ('white','brown')),
  printed_at      timestamptz not null default now(),
  printed_by      uuid default auth.uid(),
  printed_by_name text
);
create index if not exists print_logs_at_idx on public.print_logs (printed_at);

-- history of backups (manual / automatic at 00:00)
create table if not exists public.backup_logs (
  id              bigint generated by default as identity primary key,
  backup_type     text not null check (backup_type in ('manual','auto')),
  path            text not null,               -- e.g. 2569/10/23/backup_2569-10-23_103015_manual.json.gz
  size_bytes      bigint,
  row_counts      jsonb,
  created_by      uuid,
  created_by_name text,
  created_at      timestamptz not null default now()
);
create index if not exists backup_logs_at_idx on public.backup_logs (created_at desc);

