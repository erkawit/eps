create extension if not exists pg_trgm;

-- ---------------------------------------------------------------------
-- 1) Organization settings (from tblSetup) — single row only
-- ---------------------------------------------------------------------
create table if not exists public.settings (
  id              int primary key default 1 check (id = 1),
  org_name        text not null default 'ศาลจังหวัดอุดรธานี',
  address         text default 'ถนนอธิบดี ตำบลหมากแข้ง',
  amphur          text default 'เมือง',
  province        text default 'อุดรธานี',
  postcode        text default '41000',
  telephone       text default '0 4222 1993-6',
  fax             text default '0 4224 3839',
  customer_prefix text default 'CUS',          -- tblSetup.CustomerPrefix
  customer_year   boolean default true,        -- tblSetup.CustomerYear  (prefix with BE 2-digit year)
  customer_length int default 6 check (customer_length between 3 and 10),
  postage_text    text default E'ชำระค่าฝากส่งเป็นรายเดือน\nใบอนุญาตที่ ......../........\nไปรษณีย์อุดรธานี',
  show_postage    boolean default true,
  emblem_url      text,                        -- emblem (e.g. Garuda) as a data URL, optional
  show_emblem     boolean default true,
  white_offset_x  numeric default 0,           -- print calibration (mm) white envelope 4.25" x 9.25"
  white_offset_y  numeric default 0,
  brown_offset_x  numeric default 0,           -- print calibration (mm) brown envelope 8.2" x 10"
  brown_offset_y  numeric default 0,
  brown_orientation text default 'landscape' check (brown_orientation in ('landscape','portrait')),
  recipient_prefix  text default 'เรียน',
  updated_at      timestamptz default now()
);

-- upgrade path for databases created with an earlier version of this file
