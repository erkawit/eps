-- ---------------------------------------------------------------------
-- 5) Helper functions
-- ---------------------------------------------------------------------
create or replace function public.be_year() returns int
language sql stable as $$
  select (extract(year from (now() at time zone 'Asia/Bangkok'))::int + 543);
$$;

create or replace function public.is_active_user() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and active);
$$;

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and active and role = 'admin');
$$;

-- New sign-up -> profile. The very first user becomes the active admin;
-- everyone else is created as inactive staff until an admin approves them.
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
declare first_user boolean;
begin
  select not exists (select 1 from public.profiles) into first_user;
  insert into public.profiles (id, email, full_name, role, active)
  values (new.id, new.email,
          coalesce(new.raw_user_meta_data->>'full_name', split_part(new.email,'@',1)),
          case when first_user then 'admin' else 'staff' end,
          first_user);
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- Auto-generate customer code: PREFIX + BE yy + running (= id) e.g. CUS69003730
create or replace function public.customers_before_write() returns trigger
language plpgsql as $$
declare s public.settings;
begin
  if tg_op = 'INSERT' and (new.code is null or new.code = '') then
    select * into s from public.settings where id = 1;
    new.code := coalesce(s.customer_prefix,'CUS')
             || case when coalesce(s.customer_year,true) then lpad((public.be_year() % 100)::text, 2, '0') else '' end
             || lpad(new.id::text, coalesce(s.customer_length,6), '0');
  end if;
  new.updated_at := now();
  return new;
end $$;

drop trigger if exists customers_bw on public.customers;
create trigger customers_bw before insert or update on public.customers
  for each row execute function public.customers_before_write();

-- ---------------------------------------------------------------------
-- 6) Issue consecutive numbers (atomic — the book row is locked)
-- ---------------------------------------------------------------------
create or replace function public.issue_letters(
  p_book_id      int,
  p_customer_ids bigint[],
  p_subject      text default null,
  p_urgency      text default 'ปกติ',
  p_envelope     text default 'white'
) returns setof public.letters
language plpgsql security definer set search_path = public as $$
declare
  b      public.books;
  c      record;
  cur_y  int := public.be_year();
  me     text;
  new_id bigint;
  ids    bigint[] := '{}';
begin
  if not public.is_active_user() then
    raise exception 'ไม่มีสิทธิ์ใช้งาน กรุณาติดต่อผู้ดูแลระบบ';
  end if;
  if p_customer_ids is null or array_length(p_customer_ids,1) is null then
    raise exception 'กรุณาเลือกผู้รับอย่างน้อย 1 รายการ';
  end if;

  select * into b from public.books where id = p_book_id for update;
  if not found or not b.active then
    raise exception 'ไม่พบเล่มทะเบียน หรือเล่มทะเบียนถูกปิดใช้งาน';
  end if;

  if b.auto_reset and b.year < cur_y then
    update public.books set year = cur_y, next_no = 1 where id = b.id returning * into b;
  end if;

  -- never re-use a number, even if an admin moved next_no backwards
  b.next_no := greatest(b.next_no,
    (select coalesce(max(doc_no), 0) + 1 from public.letters where book_id = b.id and year = b.year));

  select coalesce(full_name, email) into me from public.profiles where id = auth.uid();

  for c in
    select cu.*, pr.name as province_name, t.name as title_name, ids.ord
    from unnest(p_customer_ids) with ordinality as ids(cid, ord)
    join public.customers cu on cu.id = ids.cid
    left join public.provinces pr on pr.id = cu.province_id
    left join public.titles t on t.id = cu.title_id
    order by ids.ord
  loop
    insert into public.letters (book_id, year, doc_no, doc_number, customer_id,
        recipient_name, recipient_address, recipient_amphur, recipient_province, recipient_postcode,
        subject, urgency, envelope, created_by, created_by_name)
    values (b.id, b.year, b.next_no, b.prefix || '/' || b.next_no, c.id,
        trim(case when coalesce(c.title_id,0) > 0 then c.title_name || ' ' else '' end || c.name),
        c.address, c.amphur, nullif(c.province_name,'-'), c.postcode,
        nullif(trim(p_subject),''), coalesce(p_urgency,'ปกติ'), coalesce(p_envelope,'white'),
        auth.uid(), me)
    returning id into new_id;
    ids := ids || new_id;
    b.next_no := b.next_no + 1;
  end loop;

  if array_length(ids,1) is null then
    raise exception 'ไม่พบข้อมูลผู้รับที่เลือก';
  end if;

  update public.books set next_no = b.next_no where id = b.id;

  return query select * from public.letters where id = any(ids) order by doc_no;
end $$;

create or replace function public.mark_printed(p_ids bigint[], p_envelope text default null)
returns int language plpgsql security definer set search_path = public as $$
declare n int; me text;
begin
  if not public.is_active_user() then raise exception 'ไม่มีสิทธิ์ใช้งาน'; end if;
  select coalesce(full_name, email) into me from public.profiles where id = auth.uid();
  update public.letters
     set status = 'printed', print_count = print_count + 1, printed_at = now(),
         envelope = coalesce(p_envelope, envelope)
   where id = any(p_ids) and status <> 'cancelled';
  get diagnostics n = row_count;
  insert into public.print_logs (letter_id, envelope, printed_by, printed_by_name)
    select id, envelope, auth.uid(), me from public.letters where id = any(p_ids) and status <> 'cancelled';
  return n;
end $$;

-- print report grouped by day / month / year (Bangkok time)
create or replace function public.print_report(p_period text, p_from date, p_to date)
returns table (period_key text, white bigint, brown bigint, total bigint, envelopes bigint)
language plpgsql stable security definer set search_path = public as $$
declare unit text; fmt text;
begin
  if not public.is_active_user() then raise exception 'ไม่มีสิทธิ์ใช้งาน'; end if;
  unit := case p_period when 'year' then 'year' when 'month' then 'month' else 'day' end;
  fmt  := case unit when 'year' then 'YYYY' when 'month' then 'YYYY-MM' else 'YYYY-MM-DD' end;
  return query
    select to_char(date_trunc(unit, l.printed_at at time zone 'Asia/Bangkok'), fmt),
           count(*) filter (where l.envelope = 'white'),
           count(*) filter (where l.envelope = 'brown'),
           count(*),
           count(distinct l.letter_id)
      from public.print_logs l
     where (l.printed_at at time zone 'Asia/Bangkok')::date between p_from and p_to
     group by 1 order by 1;
end $$;

create or replace function public.cancel_letter(p_id bigint, p_reason text)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_active_user() then raise exception 'ไม่มีสิทธิ์ใช้งาน'; end if;
  update public.letters set status = 'cancelled', cancel_reason = nullif(trim(p_reason),'')
   where id = p_id and (created_by = auth.uid() or public.is_admin());
  if not found then raise exception 'ยกเลิกได้เฉพาะเลขที่ตนเองออก (หรือผู้ดูแลระบบ)'; end if;
end $$;

-- fix recipient text printed on one envelope (number never changes)
create or replace function public.update_letter(
  p_id bigint, p_name text, p_address text, p_amphur text, p_province text,
  p_postcode text, p_subject text, p_urgency text
) returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_active_user() then raise exception 'ไม่มีสิทธิ์ใช้งาน'; end if;
  if coalesce(trim(p_name),'') = '' then raise exception 'กรุณากรอกชื่อผู้รับ'; end if;
  update public.letters set
    recipient_name = trim(p_name), recipient_address = nullif(trim(p_address),''),
    recipient_amphur = nullif(trim(p_amphur),''), recipient_province = nullif(trim(p_province),''),
    recipient_postcode = nullif(trim(p_postcode),''), subject = nullif(trim(p_subject),''),
    urgency = coalesce(nullif(p_urgency,''), urgency)
  where id = p_id and status <> 'cancelled';
  if not found then raise exception 'ไม่พบรายการ หรือรายการถูกยกเลิกแล้ว'; end if;
end $$;

-- admin: mark a user's e-mail as confirmed (no confirmation e-mail needed)
create or replace function public.admin_confirm_user(p_id uuid)
returns void language plpgsql security definer set search_path = public, auth as $$
begin
  if not public.is_admin() then raise exception 'เฉพาะผู้ดูแลระบบ'; end if;
  update auth.users set email_confirmed_at = coalesce(email_confirmed_at, now()) where id = p_id;
  if not found then raise exception 'ไม่พบผู้ใช้'; end if;
end $$;

-- admin: e-mail confirmation / last sign-in of every user
create or replace function public.admin_user_auth_status()
returns table (id uuid, email_confirmed_at timestamptz, last_sign_in_at timestamptz)
language plpgsql stable security definer set search_path = public, auth as $$
begin
  if not public.is_admin() then raise exception 'เฉพาะผู้ดูแลระบบ'; end if;
  return query select u.id, u.email_confirmed_at, u.last_sign_in_at from auth.users u;
end $$;

-- per-user envelope layout (positions of text blocks), one row per save = history
create table if not exists public.envelope_layouts (
  id               bigint generated by default as identity primary key,
  user_id          uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  user_name        text,
  envelope         text not null check (envelope in ('white','brown')),
  layout           jsonb not null,
  note             text,
  source_layout_id bigint,
  source_user_name text,
  created_at       timestamptz not null default now()
);
create index if not exists envelope_layouts_user_idx on public.envelope_layouts (user_id, envelope, created_at desc);

-- print report as a list of letters (sorted by document number)
create or replace function public.print_report_items(p_from date, p_to date, p_envelope text default null)
returns table (letter_id bigint, book_id int, year int, doc_no int, doc_number text, issued_at timestamptz,
               recipient_name text, recipient_province text, subject text, status text,
               white bigint, brown bigint, prints bigint, last_printed_at timestamptz, printed_by text)
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.is_active_user() then raise exception 'ไม่มีสิทธิ์ใช้งาน'; end if;
  return query
    select t.id, t.book_id, t.year, t.doc_no, t.doc_number, t.created_at,
           t.recipient_name, t.recipient_province, t.subject, t.status,
           count(*) filter (where l.envelope = 'white'),
           count(*) filter (where l.envelope = 'brown'),
           count(*), max(l.printed_at),
           string_agg(distinct l.printed_by_name, ', ')
      from public.print_logs l
      join public.letters t on t.id = l.letter_id
     where (l.printed_at at time zone 'Asia/Bangkok')::date between p_from and p_to
       and (p_envelope is null or l.envelope = p_envelope)
     group by t.id
     order by t.book_id, t.year, t.doc_no;
end $$;

